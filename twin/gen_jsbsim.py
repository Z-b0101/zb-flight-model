"""Generate the twin's JSBSim model from params.json (via the VLM twin).

Longitudinal aero, mass, CG and planform come from params.json + the
assumption ledger in perf.py. Lateral-directional derivatives other than
roll-control power are NOT computed here: they carry over the zb_wing.xml
estimates and are tagged UNCALIBRATED. Propulsion is a thrust actuator
(R-07 placeholder) sized to the derate fit, tagged UNCALIBRATED.
"""
import os, sys, math
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from perf import Twin, A, cd_profile  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "aircraft", "zb_twin")


def build(T=None):
    T = T or Twin()
    c, b, S = T.w.cref, T.w.b, T.S
    xcg = A("x_cg_mm") / 1000
    m = T.m
    # CL(alpha) with linear lift to a gentle stall at 0.9*section CLmax
    clmax = 0.9 * A("clmax_section")
    rows_cl, rows_cd = [], []
    for a in range(-10, 21):
        cl = T.CL0 + T.CLa * a
        if cl > clmax:  # gentle post-stall droop (MH60 TE stall), ASSUMED shape
            cl = clmax - 0.02 * (cl - clmax) / T.CLa
        rows_cl.append(f"      {a:.1f} {cl:.5f}")
        cd = cd_profile(abs(cl)) + A("cd_misc") + cl * cl / (math.pi * T.AR * T.d["oswald_e"])
        if a > 12: cd += 0.01 * (a - 12)
        rows_cd.append(f"      {a:.1f} {cd:.5f}")
    rows_cl, rows_cd = "\n".join(rows_cl), "\n".join(rows_cd)
    # inertia: thin-plate estimate for structure + point masses lumped at CG (ASSUMED)
    Ixx = m * b * b / 12 * 0.55
    Iyy = m * c * c / 12 * 1.5
    Izz = Ixx + Iyy
    xml = f'''<?xml version="1.0"?>
<!-- GENERATED by twin/gen_jsbsim.py from cad/params.json design hash {T.hash}. Do not hand-edit. -->
<fdm_config name="zb_twin" version="2.0" release="ALPHA">
 <fileheader><author>Z!B twin (Claude, GM/DE)</author><filecreationdate>2026-10-14</filecreationdate>
  <description>L1 twin. Longitudinal aero from params-driven VLM. UNCALIBRATED: lateral-directional
  (except roll control power), propulsion, battery curve, hotel load.</description></fileheader>
 <metrics>
  <wingarea unit="M2">{S:.5f}</wingarea><wingspan unit="M">{b:.4f}</wingspan><chord unit="M">{c:.4f}</chord>
  <location name="AERORP" unit="M"><x>{xcg:.4f}</x><y>0</y><z>0</z></location>
  <location name="EYEPOINT" unit="M"><x>0.05</x><y>0</y><z>0.02</z></location>
  <location name="VRP" unit="M"><x>0</x><y>0</y><z>0</z></location>
 </metrics>
 <mass_balance>
  <ixx unit="KG*M2">{Ixx:.6f}</ixx><iyy unit="KG*M2">{Iyy:.6f}</iyy><izz unit="KG*M2">{Izz:.6f}</izz>
  <emptywt unit="KG">{m:.4f}</emptywt>
  <location name="CG" unit="M"><x>{xcg:.4f}</x><y>0</y><z>0</z></location>
 </mass_balance>
 <ground_reactions>
  <contact type="BOGEY" name="nose"><location unit="M"><x>0.03</x><y>0</y><z>-0.012</z></location>
   <spring_coeff unit="N/M">900</spring_coeff><damping_coeff unit="N/M/SEC">90</damping_coeff>
   <static_friction>0.6</static_friction><dynamic_friction>0.4</dynamic_friction><rolling_friction>0.05</rolling_friction></contact>
  <contact type="BOGEY" name="left"><location unit="M"><x>0.20</x><y>-0.30</y><z>-0.012</z></location>
   <spring_coeff unit="N/M">900</spring_coeff><damping_coeff unit="N/M/SEC">90</damping_coeff>
   <static_friction>0.6</static_friction><dynamic_friction>0.4</dynamic_friction><rolling_friction>0.05</rolling_friction></contact>
  <contact type="BOGEY" name="right"><location unit="M"><x>0.20</x><y>0.30</y><z>-0.012</z></location>
   <spring_coeff unit="N/M">900</spring_coeff><damping_coeff unit="N/M/SEC">90</damping_coeff>
   <static_friction>0.6</static_friction><dynamic_friction>0.4</dynamic_friction><rolling_friction>0.05</rolling_friction></contact>
 </ground_reactions>
 <external_reactions>
  <!-- R-07 placeholder: thrust actuator, T = 1.5 N x throttle (0.33721 lbf). UNCALIBRATED. -->
  <force name="thrust" frame="BODY">
   <function><product><property>fcs/throttle-pos-norm</property><value>0.33721</value></product></function>
   <location unit="M"><x>0.21</x><y>0</y><z>0</z></location>
   <direction><x>1</x><y>0</y><z>0</z></direction>
  </force>
 </external_reactions>
 <flight_control name="zb_fcs">
  <channel name="all">
   <fcs_function name="fcs/throttle-pos-norm"><function><property>fcs/throttle-cmd-norm</property></function></fcs_function>
   <fcs_function name="fcs/elevon-sym-deg"><function><product>
     <sum><property>fcs/elevator-cmd-norm</property><property>fcs/pitch-trim-cmd-norm</property></sum><value>8.0</value></product></function></fcs_function>
   <fcs_function name="fcs/elevon-diff-deg"><function><product><property>fcs/aileron-cmd-norm</property><value>8.0</value></product></function></fcs_function>
  </channel>
 </flight_control>
 <aerodynamics>
  <function name="aero/coefficient/CL"><sum>
    <table><independentVar lookup="row">aero/alpha-deg</independentVar><tableData>
{rows_cl}
    </tableData></table>
    <product><property>fcs/elevon-sym-deg</property><value>{T.CLde:.5f}</value></product></sum></function>
  <function name="aero/coefficient/CD"><sum>
    <table><independentVar lookup="row">aero/alpha-deg</independentVar><tableData>
{rows_cd}
    </tableData></table>
    <product><property>fcs/elevon-sym-deg</property><property>fcs/elevon-sym-deg</property><value>1.3e-4</value></product>
    <product><property>aero/beta-rad</property><property>aero/beta-rad</property><value>0.3</value></product></sum></function>
  <function name="aero/coefficient/Cm"><sum>
    <value>{T.Cm0:.5f}</value>
    <product><property>aero/alpha-deg</property><value>{T.Cma:.6f}</value></product>
    <product><property>fcs/elevon-sym-deg</property><value>{T.Cmde:.6f}</value></product>
    <product><property>velocities/q-aero-rad_sec</property><property>aero/ci2vel</property><value>-1.2</value></product></sum></function>
  <!-- lateral-directional: UNCALIBRATED estimates carried over from zb_wing.xml, except Cl_da from VLM -->
  <function name="aero/coefficient/CY"><product><property>aero/beta-deg</property><value>-0.004</value></product></function>
  <function name="aero/coefficient/Cl"><sum>
    <product><property>aero/beta-deg</property><value>-0.0015</value></product>
    <product><property>velocities/p-aero-rad_sec</property><property>aero/bi2vel</property><value>-0.40</value></product>
    <product><property>velocities/r-aero-rad_sec</property><property>aero/bi2vel</property><value>0.08</value></product>
    <product><property>fcs/elevon-diff-deg</property><value>{T.d["Clda_per_deg"] * A("flap_knockdown"):.6f}</value></product></sum></function>
  <function name="aero/coefficient/Cn"><sum>
    <product><property>aero/beta-deg</property><value>0.0012</value></product>
    <product><property>velocities/p-aero-rad_sec</property><property>aero/bi2vel</property><value>-0.06</value></product>
    <product><property>velocities/r-aero-rad_sec</property><property>aero/bi2vel</property><value>-0.15</value></product>
    <product><property>fcs/elevon-diff-deg</property><value>-0.00035</value></product></sum></function>
  <axis name="DRAG"><function name="aero/f/drag"><product><property>aero/qbar-area</property><property>aero/coefficient/CD</property></product></function></axis>
  <axis name="SIDE"><function name="aero/f/side"><product><property>aero/qbar-area</property><property>aero/coefficient/CY</property></product></function></axis>
  <axis name="LIFT"><function name="aero/f/lift"><product><property>aero/qbar-area</property><property>aero/coefficient/CL</property></product></function></axis>
  <axis name="ROLL"><function name="aero/f/roll"><product><property>aero/qbar-area</property><property>metrics/bw-ft</property><property>aero/coefficient/Cl</property></product></function></axis>
  <axis name="PITCH"><function name="aero/f/pitch"><product><property>aero/qbar-area</property><property>metrics/cbarw-ft</property><property>aero/coefficient/Cm</property></product></function></axis>
  <axis name="YAW"><function name="aero/f/yaw"><product><property>aero/qbar-area</property><property>metrics/bw-ft</property><property>aero/coefficient/Cn</property></product></function></axis>
 </aerodynamics>
</fdm_config>
'''
    os.makedirs(OUT, exist_ok=True)
    open(os.path.join(OUT, "zb_twin.xml"), "w").write(xml)
    return T


if __name__ == "__main__":
    T = build(); print("wrote", OUT, "hash", T.hash)
